"""
evaluate_model.py

Experiment 001 evaluation:
MFCC + XGBoost baseline

Reports:
    Accuracy
    Precision
    Recall
    F1-score
    ROC-AUC
    Confusion Matrix

The test predictions generated by train_xgboost.py are evaluated here.
"""

from __future__ import annotations

from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
    ConfusionMatrixDisplay,
    RocCurveDisplay,
)


MODEL_ROOT = Path("D:/data/week2_controlled/models")
OUTPUT_ROOT = Path("D:/data/week2_controlled/evaluation")


def load_arrays():
    y_true = np.load(MODEL_ROOT / "test_labels.npy")
    y_pred = np.load(MODEL_ROOT / "test_predictions.npy")
    y_prob = np.load(MODEL_ROOT / "test_probabilities.npy")

    return y_true, y_pred, y_prob


def main() -> None:
    y_true, y_pred, y_prob = load_arrays()

    accuracy = accuracy_score(y_true, y_pred)
    precision = precision_score(y_true, y_pred, zero_division=0)
    recall = recall_score(y_true, y_pred, zero_division=0)
    f1 = f1_score(y_true, y_pred, zero_division=0)
    auc = roc_auc_score(y_true, y_prob)

    cm = confusion_matrix(y_true, y_pred)

    print("\n========================================")
    print("Experiment 001: MFCC + XGBoost")
    print("========================================")

    print(f"Test samples : {len(y_true)}")
    print(f"Accuracy     : {accuracy:.4f}")
    print(f"Precision    : {precision:.4f}")
    print(f"Recall       : {recall:.4f}")
    print(f"F1-score     : {f1:.4f}")
    print(f"ROC-AUC      : {auc:.4f}")

    print("\nConfusion Matrix")
    print("[[TN, FP],")
    print(" [FN, TP]]")
    print(cm)

    OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)

    np.savetxt(
        OUTPUT_ROOT / "confusion_matrix.csv",
        cm,
        delimiter=",",
        fmt="%d",
    )

    metrics_text = (
        "Experiment 001: MFCC + XGBoost\n"
        f"Test samples: {len(y_true)}\n"
        f"Accuracy: {accuracy:.6f}\n"
        f"Precision: {precision:.6f}\n"
        f"Recall: {recall:.6f}\n"
        f"F1-score: {f1:.6f}\n"
        f"ROC-AUC: {auc:.6f}\n"
    )

    (OUTPUT_ROOT / "metrics.txt").write_text(
        metrics_text,
        encoding="utf-8",
    )

    # Confusion matrix plot
    disp = ConfusionMatrixDisplay(
        confusion_matrix=cm,
        display_labels=["REAL", "FAKE"],
    )

    disp.plot()
    plt.title("Experiment 001 - Confusion Matrix")
    plt.tight_layout()
    plt.savefig(
        OUTPUT_ROOT / "confusion_matrix.png",
        dpi=150,
    )
    plt.close()

    # ROC curve
    RocCurveDisplay.from_predictions(y_true, y_prob)
    plt.title("Experiment 001 - ROC Curve")
    plt.tight_layout()
    plt.savefig(
        OUTPUT_ROOT / "roc_curve.png",
        dpi=150,
    )
    plt.close()

    print("\nSaved:")
    print(OUTPUT_ROOT / "metrics.txt")
    print(OUTPUT_ROOT / "confusion_matrix.csv")
    print(OUTPUT_ROOT / "confusion_matrix.png")
    print(OUTPUT_ROOT / "roc_curve.png")


if __name__ == "__main__":
    main()
